export function makeT(lang) {
  const i = lang === 'en' ? 1 : 0;
  return (key, vars) => {
    const e = D[key];
    let s = e ? e[i] : key;
    if (vars) Object.keys(vars).forEach((k) => { s = s.split(`{${k}}`).join(String(vars[k])); });
    return s;
  };
}

// 이름을 바꾸지 않은 기본 항목이면 언어에 맞는 이름을, 아니면 저장된 이름을 그대로
export function displayName(lang, id, name) {
  const d = DEFAULT_I18N[id];
  return d && d[0] === name ? d[lang === 'en' ? 1 : 0] : name;
}
